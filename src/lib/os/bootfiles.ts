export function secureStoreClassText(): string {
  return `${PHP_HEAD}
declare(strict_types=1);

namespace RedSec\\Vault;

final class SecureStore
{
    /** @var array{store_path:string, cipher:string, tag_length:int, master_key:string, integrity:string} */
    private array $cfg;

    public function __construct(array $cfg)
    {
        if ($cfg['guard_webroot'] && is_readable(__DIR__ . '/vault/store')) {
            throw new \\RuntimeException('vault must live outside the web root');
        }
        if ($cfg['master_key'] === '') {
            throw new \\RuntimeException('REDSEC_VAULT_KEY is not sealed');
        }
        $this->cfg = $cfg;
    }

    /** store a file: AES-256-GCM encrypt + integrity tag. Returns the vault id. */
    public function put(string $name, string $bytes): string
    {
        $iv  = random_bytes(12);
        $tag = '';
        $ct  = openssl_encrypt($bytes, $this->cfg['cipher'], $this->cfg['master_key'],
                                OPENSSL_RAW_DATA, $iv, $tag, '', $this->cfg['tag_length']);
        if ($ct === false) {
            throw new \\RuntimeException('encrypt failed');
        }
        $id  = 'v' . hash('sha3-256', $name . microtime(true) . random_bytes(8));
        $rec = [
            'name'      => $name,
            'iv'        => base64_encode($iv),
            'tag'       => base64_encode($tag),
            'ct'        => base64_encode($ct),
            'integrity' => hash('sha3-256', $ct . $name),
            'at'        => time(),
        ];
        file_put_contents($this->cfg['store_path'] . '/' . $id . '.rec',
                          json_encode($rec, JSON_THROW_ON_ERROR), LOCK_EX);
        return $id;
    }

    /** read a file back — integrity is verified BEFORE decryption. */
    public function get(string $id): string
    {
        $raw = file_get_contents($this->cfg['store_path'] . '/' . basename($id) . '.rec');
        if ($raw === false) {
            throw new \\RuntimeException('record not found');
        }
        $rec = json_decode($raw, true, 8, JSON_THROW_ON_ERROR);
        $ct  = base64_decode($rec['ct'], true);
        if (!is_string($ct) || hash('sha3-256', $ct . $rec['name']) !== $rec['integrity']) {
            throw new \\RuntimeException('integrity check failed — record tampered');
        }
        $pt = openssl_decrypt($ct, $this->cfg['cipher'], $this->cfg['master_key'],
                              OPENSSL_RAW_DATA,
                              base64_decode($rec['iv'], true),
                              base64_decode($rec['tag'], true));
        if ($pt === false) {
            throw new \\RuntimeException('decrypt failed');
        }
        return $pt;
    }

    /** list what is in the vault (names + sizes only — never plaintext) */
    public function list(): array
    {
        $out = [];
        foreach (glob($this->cfg['store_path'] . '/*.rec') ?: [] as $f) {
            $rec = json_decode((string) file_get_contents($f), true);
            if (is_array($rec)) {
                $out[] = ['id' => basename($f, '.rec'), 'name' => $rec['name'],
                          'bytes' => (int) (strlen(base64_decode($rec['ct'] ?? '') ?? '')), 'at' => $rec['at'] ?? 0];
            }
        }
        return $out;
    }

    /** shred: overwrite + unlink (no soft deletes in the vault) */
    public function shred(string $id): bool
    {
        $f = $this->cfg['store_path'] . '/' . basename($id) . '.rec';
        if (!is_file($f)) return false;
        $size = (int) filesize($f);
        $fh = fopen($f, 'r+');
        if ($fh) {
            fseek($fh, 0);
            for ($w = 0; $w < $size; $w += 4096) fwrite($fh, random_bytes(4096));
            fclose($fh);
        }
        return unlink($f);
    }
}
`
}

export function vaultApiText(): string {
  return `${PHP_HEAD}
declare(strict_types=1);

// vault-api.php — the ONLY entry point into the vault. Signed-token gate:
// every request must carry X-REDSEC-Token (HMAC-SHA384, 15 min TTL).

header('Content-Type: application/json');
header('X-Content-Type-Options: nosniff');
header('Referrer-Policy: no-referrer');

$cfg = require __DIR__ . '/vault-config.php';
require __DIR__ . '/SecureStore.php';

function tokenOk(array $cfg): bool {
    $h = $_SERVER['HTTP_X_REDSEC_TOKEN'] ?? '';
    if (!is_string($h) || $h === '') return false;
    [, $mac] = explode('.', $h, 2) + ['', ''];
    $at = (int) explode('.', $h)[0];
    if ($at < time() - $cfg['token_ttl']) return false;               // expired
    $want = hash_hmac('sha384', (string) $at, $cfg['token_secret']);
    return hash_equals($want, $mac);                                   // signed
}

if (!tokenOk($cfg)) {
    http_response_code(401);
    exit(json_encode(['ok' => false, 'error' => 'unsigned or expired token']));
}

try {
    $store = new RedSec\\Vault\\SecureStore($cfg);
    $method = $_SERVER['REQUEST_METHOD'];
    $id = preg_replace('/[^a-z0-9]/i', '', (string) ($_GET['id'] ?? ''));
    echo match ($method) {
        'GET'    => $id === ''
            ? json_encode(['ok' => true, 'files' => $store->list()])
            : json_encode(['ok' => true, 'bytes' => base64_encode($store->get($id))]),
        'POST'   => (function () use ($store) {
            $name = (string) ($_POST['name'] ?? '');
            $data = (string) ($_POST['data'] ?? '');
            if ($name === '' || $data === '') throw new RuntimeException('name and data required');
            return json_encode(['ok' => true, 'id' => $store->put($name, base64_decode($data, true) ?: '')]);
        })(),
        'DELETE' => json_encode(['ok' => $store->shred($id)]),
        default  => throw new RuntimeException('method not allowed'),
    };
} catch (Throwable $e) {
    http_response_code(400);
    echo json_encode(['ok' => false, 'error' => 'vault: ' . $e->getMessage()]);
}
`
}

